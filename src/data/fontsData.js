// Helper to look up font by ID
export function getFontById(id) {
  return FONTS_DATABASE.find(f => f.id === id) || FONTS_DATABASE[0];
}

// Find pairings for a heading font
export function getPairingsForHeading(headingFontId) {
  const font = getFontById(headingFontId);
  return font.recommendedPairs.map(pair => {
    const bodyFont = getFontById(pair.fontId);
    return {
      ...pair,
      bodyFont,
    };
  });
}

// Find recommended heading fonts for a given body font (Reverse pairing)
export function getHeadingsForBody(bodyFontId) {
  const targetFont = getFontById(bodyFontId);
  const headings = [];

  FONTS_DATABASE.forEach(font => {
    const hasPair = font.recommendedPairs?.find(p => p.fontId === bodyFontId);
    if (hasPair) {
      headings.push({
        headingFont: font,
        score: hasPair.score,
        why: hasPair.why,
      });
    } else if (targetFont.reverseHeadingPairs?.includes(font.name)) {
      headings.push({
        headingFont: font,
        score: 88,
        why: `${font.name} provides distinctive visual hierarchy when paired with ${targetFont.name}.`,
      });
    }
  });

  return headings.sort((a, b) => b.score - a.score);
}
